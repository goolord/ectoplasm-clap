// Turns tools/measured-map.json (offline renders of the processor across the
// F×K plane, feedback off, default other params) into gui/src/MeasuredMap.res.
// Regenerate with:  node tools/gen-measured-map.mjs
import fs from 'fs';
const here = new URL('.', import.meta.url);
const rows = JSON.parse(fs.readFileSync(new URL('measured-map.json', here), 'utf8'));
const Fs = [...new Set(rows.map(r => r.F))].sort((a, b) => a - b);
const Ks = [...new Set(rows.map(r => r.K))].sort((a, b) => a - b);
// How long it rings: the wet level from 50 to 300 ms after the burst ends, relative to the level
// during the burst (the output is level-matched to the input, so the burst level itself says
// little). −40 dB or less is a dead stop, 0 dB rings on undiminished.
const lo = -40, hi = 0;
const cell = (F, K) => rows.find(r => r.F === F && r.K === K);
const level = [], selfOsc = [];
for (const K of Ks) for (const F of Fs) {
  const r = cell(F, K);
  const ringDb = 20 * Math.log10(Math.max(r.ring, 1e-9) / Math.max(r.burst, 1e-9));
  const l = Math.min(1, Math.max(0, (ringDb - lo) / (hi - lo)));
  level.push(l.toFixed(2));
  selfOsc.push(r.tail > 0.01 ? 'true' : 'false');
}
const fmt = a => a.join(', ');
const out = `// GENERATED by tools/gen-measured-map.mjs — do not edit by hand.
//
// Response of the actual processor across the F×K plane, measured from
// offline \`cmaj render\` runs (0.5 s noise burst, Resonance 0, other
// parameters at their defaults). Row-major: K ascending, then F ascending.

let fValues = [${fmt(Fs.map(f => f.toFixed(4)))}]
let kValues = [${fmt(Ks.map(k => k.toFixed(5)))}]

/// How long it rings after the input stops: the level 50–300 ms after a burst relative to
/// the level during it, mapped −40 dB … 0 dB to 0..1.
let level = [${fmt(level)}]

/// Kept oscillating after the input stopped.
let selfOscillating = [${fmt(selfOsc)}]

let columns = ${Fs.length}
let rows = ${Ks.length}
`;
fs.writeFileSync(new URL('../gui/src/MeasuredMap.res', here), out);
console.log('wrote', Fs.length, 'x', Ks.length);
